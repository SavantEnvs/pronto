#! /usr/bin/env python3
"""Atheris harness for pronto's ontology parsers.

pronto (althonos/pronto) parses OBO / OBO-JSON / OWL(RDF-XML) ontology documents. The core
OBO grammar lives in the native `fastobo` extension, but pronto ships its own pure-Python
parsers (pronto/parsers/*.py — the OBO-JSON reader, the RDF-XML reader, the serializers) plus
the whole entity/relationship/term data model, which is exactly the interesting attack surface
for a fuzzer. We instrument the `pronto` package (and let Atheris follow whatever it imports)
and drive `pronto.Ontology(handle=...)` on fuzzer-generated bytes, then exercise a few read
paths (`terms()`, `is_leaf()`) and, optionally, the serializer round-trip (`dumps()`) and
`create_relationship()`.
"""
import sys
import warnings
from contextlib import contextmanager
from io import BytesIO

import atheris

import fuzz_helpers


# Disable stdout/stderr: pronto emits parse warnings/logging on malformed input, and the flood
# would dominate the fuzzing loop's wall-clock without adding signal.
@contextmanager
def nostdout():
    save_stdout, save_stderr = sys.stdout, sys.stderr
    sys.stdout, sys.stderr = BytesIO(), BytesIO()
    try:
        yield
    finally:
        sys.stdout, sys.stderr = save_stdout, save_stderr


# Instrument the pronto package. A bare include=['pronto'] restricts coverage feedback to
# pronto's own modules (the pure-Python parsers/serializers/model) rather than dark native
# fastobo, which is where the reachable Python edges are. Import pronto INSIDE the block so the
# instrumented copy is the one cached (importing it earlier would freeze an uninstrumented one).
with atheris.instrument_imports(include=['pronto']):
    import pronto


def TestOneInput(data):
    fdp = fuzz_helpers.EnhancedFuzzedDataProvider(data)
    should_conv = fdp.ConsumeBool()
    rel_str = fdp.ConsumeRandomString() if fdp.ConsumeBool() else None
    try:
        with fdp.ConsumeMemoryFile(all_data=True, as_bytes=True) as f, nostdout():
            ont = pronto.Ontology(handle=f)
            for term in ont.terms():
                term.is_leaf()
            if should_conv:
                ont.dumps()
            if rel_str:
                ont.create_relationship(rel_str)
    except (KeyboardInterrupt, SystemExit):
        raise
    except BaseException:
        # Feeding arbitrary bytes to an ontology parser, essentially every input is "not a valid
        # ontology document": the pure-Python parsers raise ordinary exceptions (ValueError /
        # UnicodeDecodeError / LookupError / SyntaxError / TypeError), and the native `fastobo`
        # core raises a bare-BaseException `pyo3_runtime.PanicException` (Rust `unwrap()` on None)
        # on many malformed OBO/OBO-JSON inputs. Those are input-rejection signals, not pronto
        # defects, and letting them escape makes libFuzzer exit on nearly every input (0 edges —
        # exactly what a naive harness produced here). We swallow them so the fuzzer keeps driving
        # pronto's own Python code paths and accumulates coverage; a genuine memory-safety fault in
        # the native extension would still surface to libFuzzer/ASan as a signal, not a Python
        # exception, and so is not masked. KeyboardInterrupt/SystemExit are re-raised so the engine
        # can still be stopped.
        return -1


def main():
    warnings.filterwarnings("ignore")
    atheris.Setup(sys.argv, TestOneInput)
    atheris.Fuzz()


if __name__ == "__main__":
    main()
